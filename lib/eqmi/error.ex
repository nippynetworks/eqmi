  @doc """
  Names of a WDS verbose call end reason (`verbose_call_end_reason` TLV,
  a `%{type: t, reason: r}` map or the two integers). Returns `{type, reason}`
  with the reason as an atom, or the number when the type or reason is unknown.
  """
  @spec verbose_call_end_reason(
          %{type: integer(), reason: integer()} | integer(),
          integer() | nil
        ) ::
          {atom() | integer(), atom() | integer()}
  def verbose_call_end_reason(type_or_map, reason \\ nil)

  def verbose_call_end_reason(%{type: type, reason: reason}, nil) do
    verbose_call_end_reason(type, reason)
  end

  def verbose_call_end_reason(type, reason) do
    type_name = Map.get(@verbose_call_end_reason_types, type, type)
    reasons = Map.get(@verbose_call_end_reasons, type_name, %{})
    {type_name, Map.get(reasons, reason, reason)}
  end
